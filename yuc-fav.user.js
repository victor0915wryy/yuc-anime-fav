    function convertStr(text, toTw) {
        if (!text) return text;
        const map = toTw ? simpleMap : traditionalMap;
        let result = '';
        for (let i = 0; i < text.length; i++) {
            const char = text[i];
            result += map[char] !== undefined ? map[char] : char;
        }
        return result;
    }

    function traverseAndConvert(node, toTw) {
        if (node.nodeType === 3) {
            const newText = convertStr(node.nodeValue, toTw);
            if (newText !== node.nodeValue) {
                node.nodeValue = newText;
            }
        } else if (node.nodeType === 1) {
            const tag = node.tagName.toUpperCase();
            if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'TEXTAREA') return;
            for (let child of node.childNodes) {
                traverseAndConvert(child, toTw);
            }
        }
    }

